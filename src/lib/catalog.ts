export function parseGameVersion(raw: string): [number, number, number] {
  const cleaned = raw.trim().replace(/\+$/, "");
  const parts = cleaned.split(".").map((p) => Number.parseInt(p, 10));
  return [Number.isFinite(parts[0]) ? parts[0] : 0, Number.isFinite(parts[1]) ? parts[1] : 0, Number.isFinite(parts[2]) ? parts[2] : 0];
}

export function cmpGameVersion(a: string, b: string): number {
  const [am, ai, ap] = parseGameVersion(a);
  const [bm, bi, bp] = parseGameVersion(b);
  if (am !== bm) return am - bm;
  if (ai !== bi) return ai - bi;
  return ap - bp;
}

export function isPalworldOnePlus(v: string): boolean {
  return parseGameVersion(v)[0] >= 1;
}

/** A listed `1.0` covers every 1.0.x patch. `1.0+` covers 1.0 and later. Early Access 0.x never matches 1.0+. */
export function supportsGameVersion(listed: string[], current: string): boolean {
  if (!listed.length) return false;
  for (const l of listed) {
    if (l === current) return true;
    if (l.endsWith("+")) {
      if (cmpGameVersion(current, l.slice(0, -1)) >= 0) return true;
      continue;
    }
    const parts = l.split(".").filter(Boolean);
    const [lm, li] = parseGameVersion(l);
    const [cm, ci] = parseGameVersion(current);
    if (parts.length === 2 && lm === cm && li === ci) return true;
  }
  return false;
}

