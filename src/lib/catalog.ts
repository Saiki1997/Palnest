export function catalogBySource(source: CatalogMod["source"]) {
  return CATALOG.filter((m) => m.source === source);
}

export function searchCatalog(query: string, source?: CatalogMod["source"]) {
  const q = query.trim();
  return CATALOG.filter((m) => {
    if (source && m.source !== source) {
      const parsed = parseModQuery(q);
      if (!(parsed.source && parsed.source === m.source && parsed.sourceId)) return false;
    }
    return matchesModQuery(m, q, source);
  });
}

export function catalogToHit(mod: CatalogMod): SearchHit {
  return {
    id: mod.id,
    name: mod.name,
    author: mod.author,
    version: mod.version,
    source: mod.source,
    sourceId: mod.sourceId,
    url: mod.url,
    downloads: mod.downloads,
    description: mod.description,
    kind: mod.kind,
    updatedAt: mod.updatedAt,
    serverCompatible: mod.serverCompatible,
    gameVersions: mod.gameVersions,
    requires: mod.requires,
    files: filesForHit({
      name: mod.name,
      kind: mod.kind === "framework" ? "palschema" : mod.kind,
      files: undefined,
      sizeKb: mod.sizeKb,
      source: mod.source,
    }),
  };
}
